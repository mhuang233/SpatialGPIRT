# -------------------------
# Internal Helper functions
# -------------------------
make_sqdist_mats <- function(coords) {
  stopifnot(is.matrix(coords), ncol(coords) == 2)
  sqdist1 <- outer(coords[, 1], coords[, 1], "-")^2
  sqdist2 <- outer(coords[, 2], coords[, 2], "-")^2
  list(sqdist1 = sqdist1, sqdist2 = sqdist2)
}

make_anisotropic_kernel <- function(coords, sigma_gp, ell1, ell2, sigma_nug) {
  d <- make_sqdist_mats(coords)
  K <- sigma_gp^2 * exp(-0.5 * (d$sqdist1 / ell1^2 + d$sqdist2 / ell2^2))
  diag(K) <- diag(K) + sigma_nug^2 + 1e-8
  K
}

